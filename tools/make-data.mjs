// Writes Data.lua from the website's game data, so the addon puts talents and Legacy perks at the same positions
// in a build code as the site does (the order of talents/<class>.json and legacy.json). Run it after the site's
// game data changes:   node tools/make-data.mjs [path to wow-4e\apps\web\public\data\v1]
// TALENTS4E_SITE_DATA also sets the path. Defaults to the website repo beside the addons folder.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const here = import.meta.dirname;
const siteData = resolve(process.argv[2] ?? process.env.TALENTS4E_SITE_DATA ?? join(here, '../../../wow-4e/apps/web/public/data/v1'));
const read = (file) => JSON.parse(readFileSync(join(siteData, file), 'utf8'));

const classes = read('classes.json');
const legacy = read('legacy.json');
const talentFiles = readdirSync(join(siteData, 'talents')).filter((f) => f.endsWith('.json')).sort();

const nodes = (list) => `{ ${list.map((t) => t.id).join(', ')} }`;
// Lua string literal. The site's names are plain ASCII; quotes and backslashes are escaped anyway.
const str = (text) => `"${String(text).replace(/["\\]/g, (c) => '\\' + c)}"`;
// Per talent, in the same order as nodes: name, icon, rank count and spell for the windows; row and column (1-based)
// and the prerequisite (req: its index in the tree, 1-based, and the rank it needs) for the planner's rules.
const req = (t) => (t.requires ? `, req = { index = ${t.requires.index + 1}, rank = ${t.requires.rank} }` : '');
const talents = (list) => list.map((t) => `{ name = ${str(t.name)}, icon = ${str(t.icon)}, ranks = ${t.ranks.length}, spell = ${t.spell ?? 0}, row = ${t.row + 1}, col = ${t.col + 1}${req(t)} }`);
const lines = [
  '-- Generated by tools/make-data.mjs from the website\'s game data. Do not edit: run the tool again.',
  '-- Talent and Legacy node ids (TraitNode ids) per tree, in build-code order (row, then column), with the English',
  '-- class, tree, talent and race names, icons and rank counts for the windows, each talent row, column and',
  '-- prerequisite for the planner, and the Legacy perks that move the first talent level.',
  'local _, ns = ...',
  '',
  'ns.Data = {',
  `  build = "${classes.build}",`,
  '  classes = {',
];
const byClass = new Map();
for (const file of talentFiles) {
  const data = read(join('talents', file));
  byClass.set(data.classId, data);
}
for (const cls of classes.classes) {
  const data = byClass.get(cls.id);
  if (!data) throw new Error(`no talents file for ${cls.name}`);
  lines.push(`    [${cls.id}] = { name = "${cls.name}", icon = "classicon_${cls.slug}", -- talents from ${data.build}`);
  for (const tree of data.trees) {
    const icon = cls.trees.find((t) => t.id === tree.id)?.icon ?? '';
    lines.push(`      { id = ${tree.id}, name = "${tree.name}", icon = "${icon}", nodes = ${nodes(tree.talents)},`);
    lines.push('        talents = {', ...talents(tree.talents).map((t) => `          ${t},`), '        },', '      },');
  }
  lines.push('    },');
}
lines.push('  },', '  races = {');
for (const race of classes.races) lines.push(`    [${race.id}] = "${race.name}",`);
lines.push('  },', `  legacy = { -- from ${legacy.build}`);
// early: perks that start talent points sooner (Talented), as { [perk index] = levels per rank }.
for (const tree of legacy.trees) {
  const early = tree.perks.flatMap((p, i) => (p.earlyTalentLevels ? [`[${i + 1}] = ${p.earlyTalentLevels}`] : []));
  lines.push(`    { id = ${tree.id}, nodes = ${nodes(tree.perks)}, early = { ${early.join(', ')} } }, -- ${tree.name}`);
}
// The site's layout fingerprints per game build (classes.json "layouts"), by class id plus "legacy": a code from an
// older build whose class (or Legacy) layout differs from today's is old, the same rule as the site's
// fromOldGameVersion.
lines.push('  },', '  layouts = {');
for (const [build, prints] of Object.entries(classes.layouts ?? {})) {
  const byId = classes.classes.map((c) => `[${c.id}] = "${prints[c.slug] ?? ''}"`);
  lines.push(`    [${build}] = { ${byId.join(', ')}, legacy = "${prints.legacy ?? ''}" },`);
}
lines.push('  },', '}', '');

writeFileSync(join(here, '..', 'Data.lua'), lines.join('\n'));
console.log(`Data.lua written from ${siteData} (build ${classes.build}, ${byClass.size} classes, ${legacy.trees.length} Legacy trees)`);
